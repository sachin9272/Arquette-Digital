import React from 'react';

export const Card: React.FC<React.HTMLAttributes<HTMLDivElement> & { hoverable?: boolean }> = ({
  children,
  className = '',
  hoverable = true,
  ...props
}) => {
  return (
    <div
      className={`bg-brand-surface-card border border-brand-border rounded-xl shadow-sm transition-all duration-300 ${
        hoverable ? 'hover:shadow-md hover:border-brand-accent/40 hover:-translate-y-0.5' : ''
      } ${className}`}
      {...props}
    >
      {children}
    </div>
  );
};

export const CardHeader: React.FC<React.HTMLAttributes<HTMLDivElement>> = ({
  children,
  className = '',
  ...props
}) => {
  return (
    <div className={`p-6 pb-3 ${className}`} {...props}>
      {children}
    </div>
  );
};

